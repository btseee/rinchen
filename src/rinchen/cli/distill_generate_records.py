"""What `rinchen distill generate` records and says about a finished run (D10): the counts
file, the manifest's inputs, metrics and status, and the lines the command prints after it
translated. The files themselves are written by the command, in its order; these functions
only decide what is in them.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path
from typing import Final

from rinchen.cli.distill_generate_plan import GeneratePlan
from rinchen.cli.train_common import numbers_under
from rinchen.export.record import EXPORT_FILES
from rinchen.export.verified import VerifiedExport
from rinchen.manifest import store
from rinchen.manifest.model import ManifestFile
from rinchen.synth.select import COUNT_KEYS
from rinchen.train.distill_generate import KdResult

KD_FILE: Final = "kd.parquet"
COUNTS_FILE: Final = "counts.json"

_NUMERIC_DECODING: Final = (
    "beam_size",
    "n",
    "max_decoding_length",
    "max_source_pieces",
    "batch_size",
    "threads",
)
_COUNTERS_COVER: Final = (
    "the shards generated by this process; a shard reused from disk adds nothing"
)


def teacher_inputs(export: VerifiedExport) -> list[ManifestFile]:
    """The teacher's files and its manifest as manifest inputs, with the SHA-256
    `verify_export` took before it read them; they are never taken again."""
    return [
        *(
            ManifestFile(path=str(export.directory / name), sha256=export.sha256[name])
            for name in EXPORT_FILES
        ),
        ManifestFile(
            path=str(store.manifest_path(export.directory)),
            sha256=export.manifest_sha256,
        ),
    ]


def metrics(plan: GeneratePlan, result: KdResult) -> dict[str, float]:
    """The counts by direction and in total (`count.<scope>.<name>`), the statistics, the
    teacher's counters and the numeric decoding options."""
    return {
        **numbers_under("count", result.counts),
        **numbers_under("matches_reference", result.matches_reference),
        **numbers_under("letterless_sources", result.letterless_sources),
        **numbers_under("shards", result.shard_stats),
        **numbers_under("teacher", result.teacher_counters),
        **{
            f"decoding.{field}": float(getattr(plan.options, field))
            for field in _NUMERIC_DECODING
        },
        "shard_size": float(plan.shard_size),
    }


def status(plan: GeneratePlan, qe_status: str) -> dict[str, str]:
    """The manifest's status: that the generation finished, whether QE ran, the teacher by
    name, placement and hashes, and the decoding options as JSON text."""
    record = plan.export.record
    return {
        "generate": "ok",
        "qe": qe_status,
        "teacher.name": plan.name,
        "teacher.tag_placement": record.tag_placement,
        "teacher.checkpoint_weights_sha256": record.checkpoint.weights_sha256,
        "teacher.checkpoint_manifest_sha256": record.checkpoint.manifest_sha256,
        "teacher.model_sha256": plan.export.sha256["model.bin"],
        "decoding": json.dumps(
            asdict(plan.options), sort_keys=True, separators=(",", ":")
        ),
    }


def counts_bytes(plan: GeneratePlan, result: KdResult, qe_status: str) -> bytes:
    """The bytes of `counts.json`: the run, the teacher's identity, the options and the
    selection it used, every count, the statistics and the QE status."""
    export = plan.export
    document = {
        "fingerprint": result.fingerprint,
        "name": plan.name,
        "seed": plan.seed,
        "shard_size": plan.shard_size,
        "teacher": {
            "name": plan.name,
            "tag_placement": export.record.tag_placement,
            "sha256": dict(export.sha256),
            "manifest_sha256": export.manifest_sha256,
            "checkpoint": asdict(export.record.checkpoint),
        },
        "decoding": asdict(plan.options),
        "selection": plan.selection.model_dump(mode="json"),
        "counts": {scope: dict(counts) for scope, counts in result.counts.items()},
        "matches_reference": dict(result.matches_reference),
        "letterless_sources": dict(result.letterless_sources),
        "teacher_counters": dict(result.teacher_counters),
        "teacher_counters_cover": _COUNTERS_COVER,
        "shard_stats": dict(result.shard_stats),
        "qe_status": qe_status,
    }
    text = json.dumps(document, sort_keys=True, indent=2, ensure_ascii=False)
    return f"{text}\n".encode()


def result_lines(
    result: KdResult, qe_status: str, corpus_path: Path, manifest_path: Path
) -> list[str]:
    """What a run prints after it translated: the counts of each direction and in total,
    the diagnostics, the statistics and where the corpus and the manifest are."""
    selected = result.counts["total"]["selected"]
    return [
        *(
            f"counts {scope}: "
            + ", ".join(f"{key} {counts[key]}" for key in COUNT_KEYS)
            for scope, counts in result.counts.items()
        ),
        f"matches reference: {result.matches_reference['total']} of {selected}",
        (
            f"letterless sources: {result.letterless_sources['total']} "
            "(not sent to the teacher)"
        ),
        "teacher counters (this process only): "
        + ", ".join(f"{key} {value}" for key, value in result.teacher_counters.items()),
        "shards: "
        + ", ".join(f"{key} {value}" for key, value in result.shard_stats.items()),
        f"qe: {qe_status}",
        f"kd corpus: {corpus_path}",
        f"manifest: {manifest_path}",
    ]
