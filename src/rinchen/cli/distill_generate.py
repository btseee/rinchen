"""`rinchen distill generate`: have the teacher translate the authentic training sources into
a knowledge-distillation (KD) corpus (D10). Parsing, file I/O and the manifest only; the work
happens in `rinchen.train` (`kd_sources`, `generate_kd`, `TeacherTranslator`) and D6's shards
and selection under them. The command is registered on the `distill` group by
`rinchen.cli.distill`.

    rinchen distill generate --corpus C [--corpus C2 ...] --teacher E --out-dir O
        [--direction D ...] [--beam-size 4] [--n 1] [--max-decoding-length 256]
        [--max-source-pieces 256] [--batch-size 64] [--shard-size 512]
        [--device cpu|cuda] [--compute-type default] [--threads 1] [--seed 1234]
        [--name N] [--selection-config P] [--qe] [--force] [--dry-run]

`--teacher` is an export `rinchen distill export` wrote; it is verified (every file's SHA-256
against its manifest) before anything is read from it. The sources are the `src` texts of the
AUTHENTIC training rows of the corpus files (split `train`, no filter reason, no
back-translated or earlier forward-translated row), one per direction and text;
`--direction <src>-<tgt>` restricts them to some directions. The teacher's best hypothesis
becomes the KD target (`--n` above 1 keeps several and lets the selection vote among them);
the selection is `selection` of `--selection-config` (default `configs/data/synth.yaml`) and
`--qe` adds its QE floor on the pairs (real source, candidate): it is refused, never
skipped, when the scorer cannot run, and the scorer is released afterwards. `--device auto`
is not a choice (it would pick the GPU); `cuda` is the operator's explicit decision and was
never run by the tests. The beam and `--n` obey CTranslate2's rule `n <= beam size`.

A run prints the plan (the corpus files, the teacher, the sources and shards of each
direction, the decoding options, whether QE was asked for, the fingerprint that names the
shard directory and how many shards it would reuse), translates, and then prints

    counts <direction>: sources .., candidates .., .., selected ..   (and `counts total`)
    matches reference: <n> of <selected>
    letterless sources: <n> (not sent to the teacher)
    teacher counters (this process only): sources .., source_too_long .., ..
    shards: planned .., reused .., generated .., regenerated_invalid ..
    qe: ok | skipped: ...
    kd corpus: <O>/kd.parquet
    manifest: <O>/manifest.json

`matches reference` counts the KD targets equal to an authentic target of their source (a
diagnostic, never a filter). The teacher's counters cover the shards generated by THIS
process: a shard reused from disk adds nothing. The progress of each shard goes to standard
error. With `--dry-run` it prints the plan and `nothing was written`, builds no teacher and
writes nothing, not even the output directory.

It writes, under O, `kd.parquet` (the corpus, origin `ft`, label `ft:<name>`), `counts.json`,
the shards (`shards-<fingerprint>/<direction>/shard-<index>.parquet`: work files, written
before the next shard is asked for, so a rerun resumes after a crash or an interrupt) and,
last, `manifest.json` (stage `distill_generate`). The manifest's inputs are the corpus files,
the selection config and the teacher's five files and manifest, each hashed before it was
read (the teacher's digests are those `verify_export` took); its outputs are `kd.parquet`
with its rows and `counts.json`. The old manifest is removed when the translation begins, so
a run that fails or is interrupted leaves none, and a rerun reuses the shards.

Exit codes: 0; 2 for a bad option or config, an export that is not vouched for, a direction
without authentic rows, a `--qe` that cannot run, a teacher without a tag it needs, an output
directory that is an input's or holds `$` or a glob character; 3 for a missing or unreadable
corpus, no training row, a manifest that cannot be read and another stage's manifest in the
output directory; 4 when the teacher or the scorer fails; 1 when the output cannot be
written; 130 when interrupted (the shards stay; a real CTranslate2 call is a blocking C++ call
that delivers the signal only when its batch returns: unmeasured).
"""

