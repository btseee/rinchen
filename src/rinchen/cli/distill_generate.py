_OUTPUTS: Final = "KD corpus"
# This command starts no Eole: the refusal is the project's path rule for outputs.
_OUT_DIR_DOLLAR_REASON: Final = (
    "which the project's path rule for outputs refuses (a tool that is given the path "
    "later could expand it as a variable)"
)
_OUT_DIR_GLOB_REASON: Final = (
    "which the project's path rule for outputs refuses (a tool that is given the path "
    "later could read it as a glob pattern)"
)
_CORPUS: Final = "corpus file"
_SELECTION_CONFIG: Final = "selection config file"
_TOOL_PACKAGES: Final = (
    "ctranslate2",
    "sentencepiece",
    "polars",
    "sacrebleu",
    "eole",
    "torch",
)
_QE_NOT_REQUESTED: Final = "skipped: not requested"
_TEACHER_FIELD: Final = re.compile(r"TeacherOptions\.(\w+)")


class Teacher(KdTranslator, Protocol):
    """What the command needs of the teacher: a translator that reports its counters and
    can check, before any shard, that it knows the tags of its directions."""

    def check_directions(self, directions: Sequence[str]) -> None: ...


def build_teacher(export: VerifiedExport, options: TeacherOptions) -> Teacher:
    """The teacher of a verified export: a CTranslate2 model loaded on `options.device`.
    Tests replace this function."""
    return TeacherTranslator(export, options)


def build_qe_scorer(cfg: SelectionConfig) -> QEScorer | None:
    """The QE scorer of a run, or None when none exists for `cfg.qe.scorer`. It loads its
    model on first use. Tests replace this function."""
    return EoleMetricXQEScorer() if cfg.qe.scorer == "metricx_qe" else None


class _Hashed(NamedTuple):
    """The manifest entries of the inputs the command reads, taken before it read them."""

    corpus: list[ManifestFile]
    selection_config: ManifestFile


def generate_command(
    corpus: Annotated[
        list[Path],
        typer.Option(
            "--corpus",
            help=(
                "Corpus Parquet file; repeat it for more. Its authentic training rows "
                "are the sources."
            ),
        ),
    ],
    teacher: Annotated[
        Path,
        typer.Option(
            "--teacher",
            help="The export of the teacher that `rinchen distill export` wrote.",
        ),
    ],
    out_dir: Annotated[
        Path,
        typer.Option(
            "--out-dir",
            help="Output directory: the KD corpus, the counts, the shards and the manifest.",
        ),
    ],
    direction: Annotated[
        list[str] | None,
        typer.Option(
            "--direction",
            help=(
                "A direction <src_lang>-<tgt_lang> to translate (repeat it for more); "
                "default: every direction that has authentic training rows."
            ),
        ),
    ] = None,
    beam_size: Annotated[
        int, typer.Option("--beam-size", min=1, help="Beam size of the teacher.")
    ] = 4,
    n: Annotated[
        int,
        typer.Option(
            "--n",
            min=1,
            help=(
                "Hypotheses kept per source, at most the beam size; above 1 the "
                "selection votes among them."
            ),
        ),
    ] = 1,
    max_decoding_length: Annotated[
        int,
        typer.Option(
            "--max-decoding-length",
            min=1,
            help="Pieces a hypothesis may have, the end token included.",
        ),
    ] = 256,
    max_source_pieces: Annotated[
        int,
        typer.Option(
            "--max-source-pieces",
            min=1,
            help="Longest source sent to the teacher, in pieces; at most 1023.",
        ),
    ] = 256,
    batch_size: Annotated[
        int,
        typer.Option(
            "--batch-size", min=1, help="Sources the library decodes together."
        ),
    ] = 64,
    shard_size: Annotated[
        int,
        typer.Option(
            "--shard-size", min=1, help="Sources per shard, the unit of resuming."
        ),
    ] = 512,
    device: Annotated[
        Literal["cpu", "cuda"],
        typer.Option(
            "--device",
            help="Where CTranslate2 runs; never auto, which would pick the GPU.",
        ),
    ] = "cpu",
    compute_type: Annotated[
        str,
        typer.Option(
            "--compute-type",
            help="CTranslate2's compute type, such as default or int8.",
        ),
    ] = "default",
    threads: Annotated[
        int, typer.Option("--threads", min=1, help="Intra-op threads of CTranslate2.")
    ] = 1,
    seed: Annotated[
        int,
        typer.Option(
            "--seed",
            help="Names the shard directory with the other inputs; recorded in the manifest.",
        ),
    ] = 1234,
    name: Annotated[
        str | None,
        typer.Option(
            "--name",
            help=(
                "The corpus label is ft:<name>; 1 to 64 of A-Z a-z 0-9 . _ -. Default: "
                "rinchen- and 12 hex characters of the hash of model.bin."
            ),
        ),
    ] = None,
    selection_config: Annotated[
        Path,
        typer.Option(
            "--selection-config",
            help="Synth config whose `selection` section decides what is kept.",
        ),
    ] = SYNTH_CONFIG_PATH,
    qe_floor: Annotated[
        bool,
        typer.Option(
            "--qe",
            help=(
                "Also drop the candidates the QE scorer rates poorly; refused when "
                "the scorer cannot run."
            ),
        ),
    ] = False,
    force: Annotated[
        bool,
        typer.Option(
            "--force", help="Translate every shard again instead of reusing the files."
        ),
    ] = False,
    dry_run: Annotated[
        bool,
        typer.Option(
            "--dry-run",
            help=(
                "Print the plan; build no teacher and write nothing, not even the "
                "output directory."
            ),
        ),
    ] = False,
) -> None:
    """Translate the authentic training sources with the teacher into a KD corpus.

    The best hypothesis of each source is the KD target; the shards are work files, so a
    rerun resumes after the ones already written. The corpus files are read whole."""
    with rinchen_errors_as_exit_codes():
        options = _teacher_options(
            beam_size=beam_size,
            n=n,
            max_decoding_length=max_decoding_length,
            max_source_pieces=max_source_pieces,
            batch_size=batch_size,
            device=device,
            compute_type=compute_type,
            threads=threads,
        )
        reject_repeated_corpora(corpus)
        target = Path(os.path.abspath(out_dir))
        reject_dollar("output directory", out_dir, reason=_OUT_DIR_DOLLAR_REASON)
        reject_glob_characters("output directory", target, reason=_OUT_DIR_GLOB_REASON)
        # Each input is hashed before anything reads it, so that the manifest vouches for
        # the bytes the run started from (the teacher's files by `verify_export`).
        hashed = _Hashed(
            [hash_input(path, what=_CORPUS, missing=DataError) for path in corpus],
            hash_input(selection_config, what=_SELECTION_CONFIG, missing=ConfigError),
        )
        require_out_apart_from_inputs(
            out_dir,
            [*corpus, selection_config, store.manifest_path(teacher)],
            option="--out-dir",
        )
        refuse_foreign_manifest(target, GENERATE_STAGE)
        export = verify_export(teacher)
        selection = load_synth_config(selection_config).selection
        plan = make_plan(
            export,
            options,
            selection,
            sources=kd_sources(load_training_rows(corpus), direction or None),
            name=kd_name(export, name),
            shard_size=shard_size,
            seed=seed,
            qe_asked=qe_floor,
            force=force,
            corpus_files=len(corpus),
            target=target,
        )
        for line in plan_lines(plan):
            typer.echo(line)
        if dry_run:
            typer.echo("nothing was written")
            return
        for line in _generate(plan, target, hashed):
            typer.echo(line)


def _teacher_options(**given: Any) -> TeacherOptions:
    """The options of the teacher, with the library's refusals worded for the command line."""
    try:
        return TeacherOptions(**given)
    except ConfigError as error:
        text = _TEACHER_FIELD.sub(lambda m: "--" + m[1].replace("_", "-"), str(error))
        raise ConfigError(text) from error


def _generate(plan: GeneratePlan, target: Path, hashed: _Hashed) -> list[str]:
    """Translate, select and write the corpus, the counts and the manifest; the lines that
    say what came out."""
    scorer = build_qe_scorer(plan.selection) if plan.qe else None
    try:
        with _released_after(scorer):
            if plan.qe:
                _require_runnable(plan.selection, scorer)
            create_out_dir(target, what=_OUTPUTS)
            teacher = build_teacher(plan.export, plan.options)
            teacher.check_directions([source.direction for source in plan.sources])
            # The manifest goes before the first translation: a run that fails or is
            # interrupted leaves none, and its shards are what a rerun resumes from.
            begin_commit(target, GENERATE_STAGE)
            result = generate_kd(
                plan.sources,
                teacher,
                plan.export,
                plan.options,
                plan.selection,
                scorer,
                out_dir=target,
                shard_size=plan.shard_size,
                seed=plan.seed,
                name=plan.name,
                force=plan.force,
                progress=_report_shard,
            )
            qe_status = result.qe_status if plan.qe else _QE_NOT_REQUESTED
            manifest = _commit(target, plan, hashed, result, qe_status)
    except OSError as exc:
        exit_cannot_write(target, exc, what=_OUTPUTS)
    return records.result_lines(result, qe_status, target / records.KD_FILE, manifest)


def _require_runnable(selection: SelectionConfig, scorer: QEScorer | None) -> None:
    reason = qe.skip_reason(selection.qe, scorer)
    if reason is not None:
        raise ConfigError(f"--qe was asked for but the QE scorer cannot run: {reason}")


@contextmanager
def _released_after(scorer: QEScorer | None) -> Iterator[None]:
    """Give the scorer's model back after the block, also after a failure."""
    try:
        yield
    finally:
        if isinstance(scorer, Releasable):
            scorer.release()


def _report_shard(progress: ShardProgress) -> None:
    how = "reused" if progress.reused else "generated"
    typer.echo(
        f"shard {progress.direction} {progress.index + 1}/{progress.total} {how}",
        err=True,
    )


def _commit(
    target: Path, plan: GeneratePlan, hashed: _Hashed, result: KdResult, qe_status: str
) -> Path:
    """Write the corpus and the counts, then the manifest, which comes last so that it never
    describes outputs that are not there."""
    corpus_path = target / records.KD_FILE
    counts_path = target / records.COUNTS_FILE
    rows = write_corpus(result.corpus, corpus_path)
    replace_file(counts_path, records.counts_bytes(plan, result, qe_status))
    return write_manifest(
        target,
        stage=GENERATE_STAGE,
        config_sha256=hashed.selection_config.sha256,
        seed=plan.seed,
        inputs=[
            *hashed.corpus,
            hashed.selection_config,
            *records.teacher_inputs(plan.export),
        ],
        outputs=[output_file(corpus_path, rows), output_file(counts_path, None)],
        metrics=records.metrics(plan, result),
        packages=_TOOL_PACKAGES,
        status=records.status(plan, qe_status),
    )
